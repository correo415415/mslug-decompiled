#!/usr/bin/env python3
"""
gen_mrom_asm.py - bootstrap the Z80 sound-driver sources from rom/201-m1.bin.

The M-ROM (128 KiB) is laid out as:

    file 0x00000-0x07FFF   fixed region, mapped at Z80 0x0000-0x7FFF
    file 0x08000-0x1FFFF   7 x 16 KiB banks, any of them mapped at 0x8000-0xBFFF
                           (window selected via reads from ports 0x08..0x0B)

This script runs z80dasm on each region and writes one raw .s per region
into mrom/asm/raw/ (fixed_0000.s, bank1_8000.s ... bank7_8000.s).  Labels are
generated by z80dasm (lXXXXh / sub_XXXXh).  mrom/tools/build_mrom.py then
assembles every region with z80asm and glues them back into 201-m1.bin.

The raw files are the starting point: they are progressively split into
mrom/asm/<subsystem>/*.s with semantic names (see mrom/README.md).  Only
regions NOT yet covered by a hand-named file are regenerated here, so the
script is safe to re-run.
"""
import os, subprocess, sys, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROM  = os.path.join(ROOT, "rom", "201-m1.bin")
RAW  = os.path.join(ROOT, "mrom", "asm", "raw")

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mrom_regions import REGIONS  # noqa: E402
_UNUSED = [
    ("fixed_0000", 0x00000, 0x8000, 0x0000),
] + [(f"bank{i}_8000", i * 0x4000, 0x4000, 0x8000) for i in range(1, 8)]


def disasm(blob: bytes, org: int) -> str:
    tmp = "/tmp/_mrom_region.bin"
    with open(tmp, "wb") as f:
        f.write(blob)
    out = subprocess.run(["z80dasm", "-a", "-l", "-g", f"0x{org:04x}", tmp],
                         capture_output=True, text=True, check=True).stdout
    lines = []
    for ln in out.splitlines():
        if ln.startswith("; z80dasm") or ln.startswith("; command line"):
            continue
        lines.append(ln)
    return "\n".join(lines).strip() + "\n"


def main():
    if not os.path.exists(ROM):
        sys.exit(f"missing {ROM} - run scripts/setup_mrom.sh")
    rom = open(ROM, "rb").read()
    assert len(rom) == 0x20000, len(rom)
    os.makedirs(RAW, exist_ok=True)
    for name, off, size, org in REGIONS:
        path = os.path.join(RAW, name + ".s")
        body = disasm(rom[off:off + size], org)
        header = (f"; {name}.s - raw z80dasm output of 201-m1.bin[{off:#07x}..{off+size:#07x}]\n"
                  f"; mapped at Z80 {org:#06x}.  Generated by mrom/tools/gen_mrom_asm.py.\n"
                  f"; Do not edit: carve functions out into mrom/asm/<subsystem>/ instead.\n\n")
        with open(path, "w") as f:
            f.write(header + body)
        n = sum(1 for l in body.splitlines() if l.startswith("\t"))
        print(f"[gen_mrom_asm] {name}.s  {size:#x} B  {n} lines")


if __name__ == "__main__":
    main()
