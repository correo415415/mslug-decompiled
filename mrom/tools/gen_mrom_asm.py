#!/usr/bin/env python3
"""
gen_mrom_asm.py - bootstrap the Z80 sound-driver sources from rom/201-m1.bin.

The M-ROM (128 KiB) is laid out as:

    file 0x00000-0x07FFF   fixed region, mapped at Z80 0x0000-0x7FFF
    file 0x08000-0x1FFFF   7 x 16 KiB banks, any of them mapped at 0x8000-0xBFFF
                           (window selected via reads from ports 0x08..0x0B)

This script runs z80dasm on each region and writes one raw .s per region
into mrom/asm/raw/fixed_0000.s (the banks 2..7 hold only sound data, decoded
by mrom/tools/gen_sound_data.py into mrom/sound/).  Labels are
generated by z80dasm (lXXXXh / sub_XXXXh).  mrom/tools/build_mrom.py then
assembles every region with z80asm and glues them back into 201-m1.bin.

The raw files are the starting point: they are progressively split into
mrom/asm/<subsystem>/*.s with semantic names (see mrom/README.md).

Per-region code/data block definitions (mrom/map/<region>_blocks.txt, z80dasm
-b format) and symbol names (mrom/map/<region>_syms.txt, z80dasm -S format)
are applied automatically when present, so data ends up as defb/defw and
known routines get their semantic names already in the raw output.
"""
import os, subprocess, sys, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROM  = os.path.join(ROOT, "rom", "201-m1.bin")
RAW  = os.path.join(ROOT, "mrom", "asm", "raw")
MAP  = os.path.join(ROOT, "mrom", "map")   # <region>_blocks.txt / <region>_syms.txt (optional)

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mrom_regions import REGIONS  # noqa: E402
_UNUSED = [
    ("fixed_0000", 0x00000, 0x8000, 0x0000),
] + [(f"bank{i}_8000", i * 0x4000, 0x4000, 0x8000) for i in range(1, 8)]


def disasm(blob: bytes, org: int, name: str) -> str:
    tmp = "/tmp/_mrom_region.bin"
    with open(tmp, "wb") as f:
        f.write(blob)
    cmd = ["z80dasm", "-a", "-l", "-g", f"0x{org:04x}"]
    # z80dasm resolves -b/-S paths relative to the cwd, so run it from mrom/map.
    blocks = os.path.join(MAP, name + "_blocks.txt")
    syms = os.path.join(MAP, name + "_syms.txt")
    if os.path.exists(blocks):
        cmd += ["-b", os.path.basename(blocks)]
    if os.path.exists(syms):
        cmd += ["-S", os.path.basename(syms)]
    out = subprocess.run(cmd + [tmp], capture_output=True, text=True, check=True,
                         cwd=MAP if os.path.isdir(MAP) else None).stdout
    lines = []
    for ln in out.splitlines():
        if ln.startswith("; z80dasm") or ln.startswith("; command line"):
            continue
        lines.append(ln)
    return "\n".join(lines).strip() + "\n"


# ---- constant fix-up --------------------------------------------------------
# z80dasm turns every 16-bit immediate that falls inside the region into a
# label reference (`ld de,l2735h`, `ld de,l0014h+1`, `ld hl,Reset_0000`), and
# then emits those labels in the middle of unrelated code/data.  Immediates
# that are not addresses -- YM2610 register/value pairs passed to RST 8, struct
# offsets / sizes / counts -- are rewritten as numeric literals with a comment,
# and labels that end up unreferenced are dropped.  Bytes are unchanged.
REAL_PTRS = {0x20de: "BankPtrTable_0080+4", 0x2131: "BankPtrTable_0080+8",
             0x1f4e: "Reset_0000"}   # push hl ; retn = jump to reset
KEEP_NAMED_MIN = 0x80        # named symbols >= this are real addresses
LD_RE = re.compile(r"^\tld (bc|de|hl|ix|iy),([A-Za-z_][A-Za-z_0-9]*)(\+(\d+))?(\t+;([0-9a-f]{4}))$")
INS_RE = re.compile(r"^\t(.*?)\t+;([0-9a-f]{4})$")


def load_syms(name):
    syms = {}
    path = os.path.join(MAP, name + "_syms.txt")
    if os.path.exists(path):
        for ln in open(path):
            m = re.match(r"(\w+):\s+equ\s+0x([0-9a-fA-F]+)", ln)
            if m:
                syms[m.group(1)] = int(m.group(2), 16)
    return syms


def fix_constants(body, name):
    syms = load_syms(name)
    lines = body.splitlines()
    ins = [i for i, l in enumerate(lines) if INS_RE.match(l)]
    nxt = {i: [INS_RE.match(lines[j]).group(1) for j in ins[k + 1:k + 3]] for k, i in enumerate(ins)}
    n = 0
    for i in ins:
        m = LD_RE.match(lines[i])
        if not m:
            continue
        reg, lab, off, tail, addr = m.group(1), m.group(2), int(m.group(4) or 0), m.group(5), int(m.group(6), 16)
        lm = re.match(r"l([0-9a-f]{4})h$", lab)
        base = int(lm.group(1), 16) if lm else syms.get(lab)
        if base is None:
            continue
        v = base + off
        after = nxt[i]
        ym = any(a.startswith("rst 8") for a in after) and reg == "de"
        if addr in REAL_PTRS:
            new, why = REAL_PTRS[addr], None
        elif ym:
            new, why = f"0{v:04x}h", f"YM reg {v >> 8:02X}h <- {v & 0xFF:02X}h"
        elif (lm and v < 0x100) or (not lm and base < KEEP_NAMED_MIN) or v == 0x1000:   # 1000h = pitch octave step
            new, why = f"0{v:04x}h", "constant"
        else:
            continue
        lines[i] = f"\tld {reg},{new}" + tail.replace(f";{addr:04x}", f";{addr:04x}" + (f"  {why}" if why else ""))
        n += 1
    text = "\n".join(lines)
    # drop lXXXXh labels that are no longer referenced
    dropped = 0
    out = []
    for l in text.splitlines():
        m = re.match(r"^(l[0-9a-f]{4}h):$", l)
        if m and not re.search(r"\b" + m.group(1) + r"\b(?!:)", text):
            dropped += 1
            continue
        out.append(l)
    # name the remaining local branch targets after the routine containing them:
    # lXXXXh -> <Routine>_L<XXXX> (the routine = last named label above it)
    ren, owner = {}, None
    for l in out:
        m = re.match(r"^([A-Za-z_][A-Za-z_0-9]*):$", l)
        if not m:
            continue
        lab = m.group(1)
        lm = re.match(r"^l([0-9a-f]{4})h$", lab)
        if lm and owner:
            ren[lab] = f"{owner}_L{lm.group(1).upper()}"
        elif not lm:
            owner = re.sub(r"_[0-9A-F]{4}$", "", re.sub(r"_L[0-9A-F]{4}$", "", lab))
    text = "\n".join(out) + "\n"
    if ren:
        text = re.sub(r"\bl[0-9a-f]{4}h\b", lambda m: ren.get(m.group(0), m.group(0)), text)
    print(f"[gen_mrom_asm] {name}: {n} immediates rewritten as constants, {dropped} spurious labels "
          f"dropped, {len(ren)} local labels named <Routine>_L<addr>")
    return text


DEFB_RE = re.compile(r"^\tdefb ([0-9a-f]{3}h)\t\t;([0-9a-f]{4})$")


def compact_data(text, per=16):
    """Pack runs of one-byte `defb XXh ;addr` lines into rows of up to `per`
    bytes (rows break at labels, at any other line and at 16-byte boundaries)."""
    out, run = [], []

    def flush():
        if run:
            out.append("\tdefb " + ",".join(b for b, _ in run) + f"\t\t;{run[0][1]:04x}")
            run.clear()

    for line in text.splitlines():
        m = DEFB_RE.match(line)
        if m:
            addr = int(m.group(2), 16)
            if run and (addr != run[-1][1] + 1 or addr % per == 0 or len(run) >= per):
                flush()
            run.append((m.group(1), addr))
        else:
            flush()
            out.append(line)
    flush()
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


def main():
    if not os.path.exists(ROM):
        sys.exit(f"missing {ROM} - run scripts/setup_mrom.sh")
    rom = open(ROM, "rb").read()
    assert len(rom) == 0x20000, len(rom)
    os.makedirs(RAW, exist_ok=True)
    for name, off, size, org in REGIONS:
        if off >= 0x8000:
            continue   # banks 2..7 are sound data: mrom/tools/gen_sound_data.py
        path = os.path.join(RAW, name + ".s")
        body = compact_data(fix_constants(disasm(rom[off:off + size], org, name), name))
        header = (f"; {name}.s - raw z80dasm output of 201-m1.bin[{off:#07x}..{off+size:#07x}]\n"
                  f"; mapped at Z80 {org:#06x}.  Generated by mrom/tools/gen_mrom_asm.py\n"
                  f"; (code/data blocks: mrom/map/{name}_blocks.txt, names: mrom/map/{name}_syms.txt).\n"
                  f"; Do not edit by hand: edit the map files and re-run the generator, or carve\n"
                  f"; functions out into mrom/asm/<subsystem>/ instead.\n\n")
        with open(path, "w") as f:
            f.write(header + body)
        n = sum(1 for l in body.splitlines() if l.startswith("\t"))
        print(f"[gen_mrom_asm] {name}.s  {size:#x} B  {n} lines")


if __name__ == "__main__":
    main()
