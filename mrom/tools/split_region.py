#!/usr/bin/env python3
"""
split_region.py - split a raw z80dasm region file into per-subsystem sources.

Reads mrom/asm/raw/<region>.s (generated by gen_mrom_asm.py) and a split
table mrom/map/<region>_split.txt with lines

    start_hex  end_hex  subdir/filename.s  [incbin=FILE]   ; comment

With incbin=FILE the piece only keeps its first label and includes the bytes
from FILE (built by another tool before z80asm runs; see build_mrom.py).

and writes one file per line into mrom/asm/<subdir>/<filename>.s containing
exactly the instructions/data whose address lies in [start, end).  The
top-level region file mrom/asm/<region>.s is rewritten to the `org`, the
shared `equ` block and one `include` per piece, in address order.  Any gap
not covered by the table stays in mrom/asm/raw/<region>_rest_XXXX.s pieces so
the build remains byte-identical.

    python3 mrom/tools/split_region.py fixed_0000
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ASM = os.path.join(ROOT, "mrom", "asm")
RAW = os.path.join(ASM, "raw")
MAP = os.path.join(ROOT, "mrom", "map")

ADDR_RE = re.compile(r";([0-9a-f]{4})$")


def parse_raw(path):
    """Return (header_lines, equ_lines, items) where items = [(addr, [lines])].

    Labels are attached to the following addressed line.  The region's
    `org` line is kept out of the items."""
    header, equs, items, pending = [], [], [], []
    org = None
    for ln in open(path):
        ln = ln.rstrip("\n")
        if not items and not pending and ln.startswith(";"):
            header.append(ln); continue
        if ln.startswith("org"):
            org = ln; continue
        if re.match(r"^\S+:\s+equ\s", ln):
            equs.append(ln); continue
        if ln.strip() == "":
            continue
        m = ADDR_RE.search(ln)
        if m and ln.startswith("\t"):
            items.append((int(m.group(1), 16), pending + [ln])); pending = []
        else:
            pending.append(ln)   # label (or comment) for the next instruction
    if pending:
        items.append((items[-1][0] + 1 if items else 0, pending))
    return header, org, equs, items


def main():
    region = sys.argv[1] if len(sys.argv) > 1 else "fixed_0000"
    raw = os.path.join(RAW, region + ".s")
    split = os.path.join(MAP, region + "_split.txt")
    header, org, equs, items = parse_raw(raw)

    table, incbins = [], {}
    for ln in open(split):
        ln = ln.split(";", 1)[0].strip()
        if not ln:
            continue
        f = ln.split()
        s, e, name = f[:3]
        inc = f[3][len("incbin="):] if len(f) > 3 and f[3].startswith("incbin=") else None
        table.append((int(s, 16), int(e, 16), name))
        if inc:
            incbins[name] = inc
    table.sort()

    # fill gaps with raw rest pieces
    pieces, cur = [], items[0][0]
    end_all = items[-1][0] + 1
    for s, e, name in table:
        if s > cur:
            pieces.append((cur, s, f"raw/{region}_rest_{cur:04x}.s"))
        pieces.append((s, e, name)); cur = e
    if cur < end_all:
        pieces.append((cur, end_all, f"raw/{region}_rest_{cur:04x}.s"))

    written = []
    for s, e, name in pieces:
        body = [l for a, ls in items if s <= a < e for l in ls]
        if not body:
            continue
        if name in incbins:
            # data owned by another source tree (assembled to a binary first):
            # keep only the labels of the range and pull the bytes in.
            labels = [l for a, ls in items if s <= a < e for l in ls if not l.startswith("\t")]
            assert len(labels) <= 1 and all(l.endswith(":") for l in labels), labels
            body = labels + [f'\tincbin "{incbins[name]}"\t\t; {e - s:#x} bytes, {s:04x}-{e:04x}']
        path = os.path.join(ASM, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(f"; {os.path.basename(name)} - M-ROM {region} [{s:#06x}..{e:#06x})\n"
                    f"; Carved from mrom/asm/raw/{region}.s by mrom/tools/split_region.py.\n"
                    f"; Assembled through mrom/asm/{region}.s; must stay byte-identical.\n\n")
            f.write("\n".join(body) + "\n")
        written.append((s, e, name))

    top = os.path.join(ASM, region + ".s")
    with open(top, "w") as f:
        f.write(f"; {region}.s - top-level source for M-ROM region {region}\n"
                f"; Generated by mrom/tools/split_region.py from mrom/map/{region}_split.txt.\n"
                f"; Build: python3 mrom/tools/build_mrom.py  (must report IDENTICA)\n\n")
        f.write(org + "\n\n")
        f.write('include "neogeo_z80.inc"\t\t; hardware ports / YM2610 registers (mrom/include)\n\n')
        if equs:
            f.write("; ---- RAM / constant equates (from mrom/map/" + region + "_syms.txt) ----\n")
            f.write("\n".join(equs) + "\n\n")
        for s, e, name in written:
            f.write(f'include "{name}"\t\t; {s:04x}-{e:04x}\n')
    print(f"[split_region] {region}: {len(written)} pieces -> {os.path.relpath(top, ROOT)}")
    for s, e, name in written:
        print(f"  {s:04x}-{e:04x}  {name}")


if __name__ == "__main__":
    main()
